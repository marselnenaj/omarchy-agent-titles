const { readFileSync } = require('node:fs');
const { runInNewContext } = require('node:vm');
const assert = require('node:assert/strict');
const model = {};
runInNewContext(readFileSync(`${__dirname}/../TitleModel.js`, 'utf8'), model);
const monitor = { x: 3840, y: 0, activeWorkspace: { id: 5 }, specialWorkspace: { id: 0 } };
const client = { address: '0x1', class: 'com.mitchellh.ghostty', title: '✳ Sample project', monitor: 1, workspace: { id: 5 }, at: [4927, 973], size: [1061, 907], mapped: true, focusHistoryID: 1 };
assert.equal(model.agentTitle(client).title, 'Sample project');
assert.equal(model.agentTitle(client).provider, 'Claude');
assert.equal(model.agentTitle({ ...client, title: '⠹ Server maintenance | Example' }).provider, 'Codex');
assert.equal(model.agentTitle({ ...client, title: '◐ Example app' }).title, 'Example app');
assert.equal(model.agentTitle({ ...client, title: '~/Work' }), null);
assert.equal(model.agentTitle({ ...client, class: 'chromium' }), null);
assert.equal(model.agentTitle({ ...client, class: 'org.omarchy.agent', title: '' }).title, 'AI');
const label = model.labelFor(client, monitor, [client]);
assert.equal(label.x, 1099);
assert.equal(label.y, 963);
assert.equal(model.labelFor({ ...client, hidden: true }, monitor, [client]), null);
assert.equal(model.labelFor({ ...client, workspace: { id: 3 } }, monitor, [client]), null);
assert.equal(model.labelFor(client, { ...monitor, specialWorkspace: { id: -98 } }, [client]), null);
assert.equal(model.labelFor(client, monitor, [client, { ...client, address: '0x2', fullscreen: 2 }]), null);
assert.ok(model.labelFor(client, monitor, [client, { ...client, address: '0x2', monitor: 0, fullscreen: 2 }]));
assert.equal(model.labelFor(client, monitor, [client, { ...client, address: '0x2', floating: true, at: [4900, 950], size: [200, 100] }]), null);
assert.ok(model.labelFor(client, monitor, [client, { ...client, address: '0x2', floating: true, at: [0, 0], size: [200, 100] }]));
assert.ok(model.labelFor({ ...client, fullscreen: 1 }, monitor, [{ ...client, fullscreen: 1 }]));
console.log('17 checks passed: title detection, monitor coordinates, workspace visibility, fullscreen, floating occlusion.');
